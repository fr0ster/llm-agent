DO BEGIN
  DECLARE ordinal_exists INTEGER;
  SELECT COUNT(*) INTO ordinal_exists FROM SYS.TABLE_COLUMNS
  WHERE SCHEMA_NAME = CURRENT_SCHEMA AND TABLE_NAME = 'RAG_DOCUMENTS' AND COLUMN_NAME = 'FRAGMENT_ORDINAL';
  IF :ordinal_exists = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE "RAG_DOCUMENTS" ADD ("FRAGMENT_ORDINAL" INTEGER DEFAULT 0 NOT NULL)';
    EXECUTE IMMEDIATE 'ALTER TABLE "RAG_DOCUMENTS" ALTER ("TEXT" NCLOB NULL)';
    EXECUTE IMMEDIATE 'ALTER TABLE "RAG_DOCUMENTS" DROP PRIMARY KEY';
    EXECUTE IMMEDIATE 'ALTER TABLE "RAG_DOCUMENTS" ADD PRIMARY KEY ("COLLECTION", "ID", "FRAGMENT_ORDINAL")';
  END IF;
END;
