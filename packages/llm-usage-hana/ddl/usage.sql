CREATE TABLE USAGE_RECORDS (
  "id" NVARCHAR(512) PRIMARY KEY,
  "schema_version" INTEGER NOT NULL,
  "at" BIGINT NOT NULL,
  "kind" NVARCHAR(512) NOT NULL,
  "session_id" NVARCHAR(512),
  "user_id" NVARCHAR(512),
  "turn_id" NVARCHAR(512),
  "task_id" NVARCHAR(512),
  "role" NVARCHAR(512),
  "destination" NVARCHAR(512),
  "outcome" NVARCHAR(512) NOT NULL,
  "record_json" NCLOB NOT NULL
);
CREATE INDEX USAGE_RECORDS_AT_IDX ON USAGE_RECORDS ("at");
CREATE INDEX USAGE_RECORDS_SESSION_ID_IDX ON USAGE_RECORDS ("session_id");
CREATE INDEX USAGE_RECORDS_KIND_IDX ON USAGE_RECORDS ("kind");
