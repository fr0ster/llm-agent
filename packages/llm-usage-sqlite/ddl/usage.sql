CREATE TABLE IF NOT EXISTS USAGE_RECORDS (
  id TEXT PRIMARY KEY,
  schema_version INTEGER NOT NULL,
  at BIGINT NOT NULL,
  kind TEXT NOT NULL,
  session_id TEXT,
  user_id TEXT,
  turn_id TEXT,
  task_id TEXT,
  role TEXT,
  destination TEXT,
  outcome TEXT NOT NULL,
  record_json TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS USAGE_RECORDS_AT_IDX ON USAGE_RECORDS (at);
CREATE INDEX IF NOT EXISTS USAGE_RECORDS_SESSION_ID_IDX ON USAGE_RECORDS (session_id);
CREATE INDEX IF NOT EXISTS USAGE_RECORDS_KIND_IDX ON USAGE_RECORDS (kind);
